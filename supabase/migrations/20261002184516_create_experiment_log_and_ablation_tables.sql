/*
# Create experiment log and ablation results tables

## Purpose
This Churn Prediction Lab app trains ML models and logs every training run as a structured
experiment entry. Previously stored in browser localStorage only, these tables move experiment
logs and ablation study results to the Supabase database so they persist across devices and
browser sessions.

## 1. New Tables

### experiments
Stores one row per model trained during a training run. Each training run that trains 4 models
(naive baseline, logistic regression, random forest, gradient boosting) produces 4 rows.
- `id` (text, primary key) — unique experiment ID generated by the app (e.g. "exp-1696200000000-logistic")
- `run_id` (text, not null) — groups experiments from the same training run together
- `timestamp` (timestamptz, not null) — when the experiment was logged
- `model_type` (text, not null) — one of: naive, logistic, randomForest, gradientBoosting
- `model_name` (text, not null) — human-readable model name
- `hyperparameters` (jsonb, not null) — model hyperparameters as a JSON object
- `roc_auc` (double precision, not null) — ROC-AUC score
- `pr_auc` (double precision, not null) — PR-AUC score
- `mae` (double precision, not null) — Mean Absolute Error
- `accuracy` (double precision, not null) — accuracy score
- `f1` (double precision, not null) — F1 score
- `cv_mean` (double precision, not null) — cross-validation mean ROC-AUC
- `cv_std` (double precision, not null) — cross-validation std dev
- `dataset_size` (integer, not null) — number of rows in the dataset used
- `feature_count` (integer, not null) — number of features used
- `created_at` (timestamptz, default now()) — row insertion time

### ablation_results
Stores one row per feature-group-removed ablation experiment, plus one baseline row.
- `id` (uuid, primary key) — auto-generated
- `run_id` (text, not null) — groups ablation results from the same study run
- `feature_group` (text, not null) — name of the feature group removed (or "Full Model" for baseline)
- `features_removed` (jsonb, not null) — array of feature names that were removed (empty for baseline)
- `is_baseline` (boolean, not null, default false) — true for the full-model baseline row
- `roc_auc` (double precision, not null) — ROC-AUC with this group removed
- `pr_auc` (double precision, not null) — PR-AUC with this group removed
- `mae` (double precision, not null) — MAE with this group removed
- `accuracy` (double precision, not null) — accuracy with this group removed
- `f1` (double precision, not null) — F1 with this group removed
- `delta_roc_auc` (double precision, not null) — change in ROC-AUC vs baseline
- `delta_pr_auc` (double precision, not null) — change in PR-AUC vs baseline
- `created_at` (timestamptz, default now()) — row insertion time

## 2. Security
- This is a single-tenant app with NO sign-in screen. All data is intentionally public/shared.
- RLS is enabled on both tables.
- Policies allow anon + authenticated full CRUD (SELECT, INSERT, UPDATE, DELETE) on both tables.
- USING (true) is acceptable here because the data is intentionally public (no auth, no user isolation).

## 3. Indexes
- `experiments_run_id_idx` on experiments(run_id) — to fetch all experiments from a training run
- `experiments_timestamp_idx` on experiments(timestamp DESC) — for sorted history display
- `experiments_model_type_idx` on experiments(model_type) — for filtering by model
- `ablation_results_run_id_idx` on ablation_results(run_id) — to fetch all ablation results from a study
*/

-- ============ experiments table ============
CREATE TABLE IF NOT EXISTS experiments (
  id text PRIMARY KEY,
  run_id text NOT NULL,
  timestamp timestamptz NOT NULL,
  model_type text NOT NULL,
  model_name text NOT NULL,
  hyperparameters jsonb NOT NULL DEFAULT '{}'::jsonb,
  roc_auc double precision NOT NULL DEFAULT 0,
  pr_auc double precision NOT NULL DEFAULT 0,
  mae double precision NOT NULL DEFAULT 0,
  accuracy double precision NOT NULL DEFAULT 0,
  f1 double precision NOT NULL DEFAULT 0,
  cv_mean double precision NOT NULL DEFAULT 0,
  cv_std double precision NOT NULL DEFAULT 0,
  dataset_size integer NOT NULL DEFAULT 0,
  feature_count integer NOT NULL DEFAULT 0,
  created_at timestamptz DEFAULT now()
);

ALTER TABLE experiments ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "anon_select_experiments" ON experiments;
CREATE POLICY "anon_select_experiments"
  ON experiments FOR SELECT
  TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "anon_insert_experiments" ON experiments;
CREATE POLICY "anon_insert_experiments"
  ON experiments FOR INSERT
  TO anon, authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "anon_update_experiments" ON experiments;
CREATE POLICY "anon_update_experiments"
  ON experiments FOR UPDATE
  TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "anon_delete_experiments" ON experiments;
CREATE POLICY "anon_delete_experiments"
  ON experiments FOR DELETE
  TO anon, authenticated USING (true);

CREATE INDEX IF NOT EXISTS experiments_run_id_idx ON experiments(run_id);
CREATE INDEX IF NOT EXISTS experiments_timestamp_idx ON experiments(timestamp DESC);
CREATE INDEX IF NOT EXISTS experiments_model_type_idx ON experiments(model_type);

-- ============ ablation_results table ============
CREATE TABLE IF NOT EXISTS ablation_results (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  run_id text NOT NULL,
  feature_group text NOT NULL,
  features_removed jsonb NOT NULL DEFAULT '[]'::jsonb,
  is_baseline boolean NOT NULL DEFAULT false,
  roc_auc double precision NOT NULL DEFAULT 0,
  pr_auc double precision NOT NULL DEFAULT 0,
  mae double precision NOT NULL DEFAULT 0,
  accuracy double precision NOT NULL DEFAULT 0,
  f1 double precision NOT NULL DEFAULT 0,
  delta_roc_auc double precision NOT NULL DEFAULT 0,
  delta_pr_auc double precision NOT NULL DEFAULT 0,
  created_at timestamptz DEFAULT now()
);

ALTER TABLE ablation_results ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "anon_select_ablation_results" ON ablation_results;
CREATE POLICY "anon_select_ablation_results"
  ON ablation_results FOR SELECT
  TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "anon_insert_ablation_results" ON ablation_results;
CREATE POLICY "anon_insert_ablation_results"
  ON ablation_results FOR INSERT
  TO anon, authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "anon_update_ablation_results" ON ablation_results;
CREATE POLICY "anon_update_ablation_results"
  ON ablation_results FOR UPDATE
  TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "anon_delete_ablation_results" ON ablation_results;
CREATE POLICY "anon_delete_ablation_results"
  ON ablation_results FOR DELETE
  TO anon, authenticated USING (true);

CREATE INDEX IF NOT EXISTS ablation_results_run_id_idx ON ablation_results(run_id);
